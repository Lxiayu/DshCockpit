#!/usr/bin/env bash
# scripts/poc/runtime-poc.sh — Issue #9：隔离的 Runtime & Protocol POC 环境。
#
# 第一性原理：为什么必须是"完全隔离"而不是"小心一点"
#
#   POC 要回答的问题是"能不能升级"。如果 POC 过程本身污染了生产环境，
#   那么无论结论是什么，用户都要先修环境再谈升级 —— POC 就变成了负资产。
#
#   所以这里把四样东西全部关进 /tmp 下的独立目录：
#
#     1. 目录       POC_ROOT（可删，不碰仓库与 ~/.dsh）
#     2. Profile    DSH_HOME=$POC_ROOT/dsh-home（全新，不带用户既有 profile）
#     3. Workspace  $POC_ROOT/workspace（全新 git 仓库，不碰用户的真实项目）
#     4. 测试数据   $POC_ROOT/{logs,artifacts}
#
#   并且**只读**地引用仓库里的 vendor/runtime（如果已存在），否则安装到 POC_ROOT。
#   绝不写 package.json 的 runtimeVersion，绝不动 ~/.dsh。
#
#   还有一条容易被忽略的：npm 的全局 cache 会被共用。这里显式把
#   npm_config_cache 指向 POC_ROOT，避免 POC 下载的包与用户 cache 混在一起。
#
# 用法：
#   scripts/poc/runtime-poc.sh setup   <version>   # 建隔离环境 + 安装指定版本
#   scripts/poc/runtime-poc.sh env     <version>   # 打印环境变量（供 eval）
#   scripts/poc/runtime-poc.sh verify  <version>   # 跑协议/功能验证
#   scripts/poc/runtime-poc.sh teardown <version>  # 清理
#   scripts/poc/runtime-poc.sh status              # 看现有 POC 目录
#
# 设计约束（用户 2026-11-01 明确）：
#   - 不得修改当前生产 Runtime / 真实 Settings / 用户 Workspace / 锁定版本
#   - 分别记录 0.2.1-rc.5 与 0.2.2-alpha.2
#   - 验证真实功能，不止"能启动"
#   - 未实际验证的能力必须明确标记
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
POC_BASE="${TMPDIR:-/tmp}/dsh-poc"
MANIFEST_VERSION=1

die() { echo "[poc] ERROR: $*" >&2; exit 1; }
info() { echo "[poc] $*"; }

poc_root() {
  local version="$1"
  [ -n "$version" ] || die "version required"
  echo "${POC_BASE}/${version}"
}

# 生成 POC 环境变量（source 用）。全部路径都在 POC_ROOT 之下。
write_env_file() {
  local root="$1" version="$2" file="$1/poc.env"
  cat > "$file" <<EOF
# Generated by runtime-poc.sh — POC isolation for @deepseek-ai/dsh@${version}
# Source this file to run commands inside the POC sandbox.
export POC_ROOT='${root}'
export POC_VERSION='${version}'
export DSH_HOME='${root}/dsh-home'
export DSH_WORKSPACE='${root}/workspace'
export DSH_POC_LOGS='${root}/logs'
export DSH_POC_ARTIFACTS='${root}/artifacts'
# npm cache is shared by default; pin it so POC downloads never mix with the
# user's real cache (and so teardown can reclaim the space).
export npm_config_cache='${root}/npm-cache'
export DSH_PRIMARY_RUNTIME='${root}/dsh-home'
# Belt and braces: never let a POC command resolve to the user's dsh home.
export DSH_POC_ISOLATED=1
EOF
}

cmd_setup() {
  local version="${1:?usage: setup <version>}"
  local root; root="$(poc_root "$version")"

  info "POC root:  $root"
  info "version:   $version"

  mkdir -p "$root"/{dsh-home,workspace,logs,artifacts,npm-cache}
  write_env_file "$root" "$version"

  # 全新 git 工作区（POC 的 workspace 隔离能力需要一个真仓库）
  if [ ! -d "$root/workspace/.git" ]; then
    ( cd "$root/workspace" \
      && git init -q \
      && printf '# POC workspace\n' > README.md \
      && git add README.md \
      && git -c user.email=poc@local -c user.name=poc commit -qm 'poc: seed workspace' )
    info "seeded isolated git workspace"
  fi

  # 安装 runtime：优先复用仓库里已有的 vendor/runtime（只读引用，不写回仓库）
  local vendored="${REPO_ROOT}/vendor/runtime/${version}/node_modules/@deepseek-ai/dsh"
  if [ -d "$vendored" ]; then
    local link="${root}/runtime"
    rm -rf "$link"
    ln -sfn "$(dirname "$(dirname "$(dirname "$vendored")")")" "$link"
    info "reusing vendored runtime (symlinked, repo untouched): $vendored"
  else
    info "vendored runtime for ${version} not present — installing into POC root"
    info "  (this downloads ~136MB and does NOT touch ${REPO_ROOT}/vendor)"
    ( cd "$root" \
      && npm_config_cache="$root/npm-cache" \
         npm install --no-save --no-audit --no-fund --prefix "$root/runtime-install" \
         "@deepseek-ai/dsh@${version}" ) || die "install failed"
    ln -sfn "$root/runtime-install" "$root/runtime"
  fi

  local bin; bin="$(runtime_bin "$root")"
  [ -n "$bin" ] || die "cannot locate dsh bin.js after install"
  info "runtime bin: $bin"
  info "setup complete. Next: scripts/poc/runtime-poc.sh verify ${version}"
}

# 找到 POC runtime 的 bin.js（symlink 或直接目录都支持）。
runtime_bin() {
  local root="$1"
  local candidates=(
    "$root/runtime-install/node_modules/@deepseek-ai/dsh/lib/bin.js"
    "$root/runtime/node_modules/@deepseek-ai/dsh/lib/bin.js"
  )
  for c in "${candidates[@]}"; do
    [ -f "$c" ] && { echo "$c"; return 0; }
  done
  # symlink 指向 vendor/runtime/<v>，其内部结构是 node_modules/@deepseek-ai/dsh
  if [ -L "$root/runtime" ]; then
    local real; real="$(cd "$root/runtime" && pwd -P)"
    [ -f "$real/node_modules/@deepseek-ai/dsh/lib/bin.js" ] && { echo "$real/node_modules/@deepseek-ai/dsh/lib/bin.js"; return 0; }
  fi
  echo ""
}

cmd_env() {
  local version="${1:?usage: env <version>}"
  local root; root="$(poc_root "$version")"
  [ -f "$root/poc.env" ] || die "run 'setup ${version}' first"
  cat "$root/poc.env"
}

cmd_status() {
  info "POC base: $POC_BASE"
  if [ ! -d "$POC_BASE" ]; then info "(no POC environments)"; return 0; fi
  for d in "$POC_BASE"/*/; do
    [ -d "$d" ] || continue
    local v; v="$(basename "$d")"
    local size; size="$(du -sh "$d" 2>/dev/null | cut -f1)"
    local log="$d/logs/verify.md"
    if [ -f "$log" ]; then
      printf '  %-16s %6s  verified (see %s)\n' "$v" "$size" "$log"
    else
      printf '  %-16s %6s  set up, not verified\n' "$v" "$size"
    fi
  done
}

cmd_teardown() {
  local version="${1:?usage: teardown <version>}"
  local root; root="$(poc_root "$version")"
  case "$root" in
    "${POC_BASE}"/*) ;;
    *) die "refusing to remove unexpected path: $root" ;;
  esac
  [ -d "$root" ] || { info "nothing to remove at $root"; return 0; }
  info "removing $root"
  rm -rf "$root"
  info "teardown complete (production environment never touched)"
}

cmd_verify() {
  local version="${1:?usage: verify <version>}"
  local root; root="$(poc_root "$version")"
  [ -f "$root/poc.env" ] || die "run 'setup ${version}' first"
  # shellcheck disable=SC1090
  set -a; . "$root/poc.env"; set +a
  node "${REPO_ROOT}/scripts/poc/protocol-probe.js" \
    --version "$version" \
    --root "$root" \
    --out "$root/logs/verify.json" \
    --report "$root/logs/verify.md"
}

case "${1:-}" in
  setup)    shift; cmd_setup "$@" ;;
  env)      shift; cmd_env "$@" ;;
  verify)   shift; cmd_verify "$@" ;;
  teardown) shift; cmd_teardown "$@" ;;
  status)   cmd_status ;;
  *) sed -n '3,40p' "${BASH_SOURCE[0]}"; exit 2 ;;
esac
