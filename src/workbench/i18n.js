const LANGUAGES = ['zh', 'en'];

function normalizeLanguage(value) {
  const text = String(value || '').toLowerCase();
  if (text.startsWith('en')) return 'en';
  if (text.startsWith('zh')) return 'zh';
  return null;
}

// 'system' resolves through the renderer's locale; an explicit choice wins.
function resolveLanguage(preference, systemLanguage) {
  if (LANGUAGES.includes(preference)) return preference;
  return normalizeLanguage(systemLanguage) || 'zh';
}

function t(key, language = 'zh', params = null) {
  const entry = DICT[key];
  if (!entry) return key;                       // a missing key shows itself, never a blank
  const text = entry[resolveLanguage(language)] || entry.zh || key;
  if (!params) return text;
  // {name} placeholders: values are interpolated, an unknown name is left visible rather
  // than silently dropped (a half-filled sentence is worse than an obvious one)
  return text.replace(/\{(\w+)\}/g, (match, name) => (params[name] === undefined ? match : String(params[name])));
}

// One pass over the DOM: text, tooltips and placeholders, all driven by attributes.
function applyTranslations(root, language) {
  const scope = root || (typeof document !== 'undefined' ? document : null);
  if (!scope) return { applied: 0 };
  let applied = 0;
  for (const node of scope.querySelectorAll('[data-i18n]')) {
    node.textContent = t(node.dataset.i18n, language);
    applied += 1;
  }
  for (const node of scope.querySelectorAll('[data-i18n-title]')) {
    node.title = t(node.dataset.i18nTitle, language);
    applied += 1;
  }
  for (const node of scope.querySelectorAll('[data-i18n-placeholder]')) {
    node.placeholder = t(node.dataset.i18nPlaceholder, language);
    applied += 1;
  }
  for (const node of scope.querySelectorAll('[data-i18n-aria-label]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel, language));
    applied += 1;
  }
  if (scope.documentElement) scope.documentElement.lang = resolveLanguage(language) === 'en' ? 'en' : 'zh-CN';
  return { applied };
}

const wbI18nApi = { DICT, LANGUAGES, applyTranslations, normalizeLanguage, resolveLanguage, t };

if (typeof window !== 'undefined') window.wbI18n = wbI18nApi;
if (typeof module !== 'undefined' && module.exports) module.exports = wbI18nApi;
