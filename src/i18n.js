'use strict';

/** Resolve the OS locale; works in plain node (no electron) for tests. */
function appLocale() {
  try {
    const { app } = require('electron');
    if (app && typeof app.getLocale === 'function') return app.getLocale();
  } catch { /* not running under electron */ }
  return process.env.LANG || 'en';
}

