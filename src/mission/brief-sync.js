// src/mission/brief-sync.js — 把 Mission Brief 同步进 AGENTS.md（P1 的最后一环）。
//
// 第一性原理：为什么是"写入 AGENTS.md"，而不是"拦截 Session 创建时注入"
//
//   我最初的想法是：在壳创建 Session 时把 Brief 塞进 system prompt。
//   核实代码后发现这条路**不存在**，而且不该存在：
//     · main.js:406 `harnessView.loadURL(runtimeUrl)` —— 壳是官方 dsh web UI 的容器
//     · 用户是在**官方 UI 里**发 prompt 的。壳不接管输入面（AGENTS.md 铁律 5）
//     · `createSession` 只被旧的 Team Runtime 调用（team-shell-transport.js:171），
//       主路径的会话根本不经过它
//   所以"拦截注入"要么需要侵入官方 UI，要么需要重写输入路径 —— 两者都违反定位。
//
//   正确的接入点是官方**已经支持**的机制：dsh-agent-instructions 在
//   **每次 Session 启动时**读 `<workspace>/AGENTS.md` + `$DSH_HOME/AGENTS.md`。
//   把 Brief 写进 workspace 的 AGENTS.md，它就会在下次会话自动生效——
//   不需要壳去碰任何 prompt，也不需要官方做任何改动。
//
//   这是"利用官方能力而不是复制它"的直接体现。
//
// 第二性原理：为什么必须用标记块包裹，且绝不覆盖用户手写内容
//
//   AGENTS.md 是用户的项目说明文件，可能已经写了很多东西（人写的规则、
//   团队约定、构建命令）。如果 Brief 直接整文件覆盖，就是在**销毁用户数据**。
//
//   所以用一组明确的标记把 Brief 圈起来：
//     <!-- dsh-cockpit:mission-brief:begin -->
//     ...生成的 Brief...
//     <!-- dsh-cockpit:mission-brief:end -->
//   同步时只替换这两个标记之间的内容，标记之外**逐字节保留**。
//
//   三道安全阀：
//     1. 首次同步时，若文件已存在且不含标记 → 在**末尾追加**标记块，不覆盖
//     2. 替换时用"标记之间"的精确切片，不用正则整段替换（避免贪婪匹配吃掉用户内容）
//     3. 撤销同步（removeBrief）只删除标记块，不删文件
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { ensureSelfIgnore } = require('./workspace-dir');

const BEGIN_MARK = '<!-- dsh-cockpit:mission-brief:begin -->';
const END_MARK = '<!-- dsh-cockpit:mission-brief:end -->';

/** 同步状态（写进标记块内的元数据，便于判断是否需要重写）。 */
const META_PREFIX = '<!-- dsh-cockpit:meta ';

/**
 * 从 AGENTS.md 内容里取出 Brief 块。
 * @returns {{present:boolean, body:string, start:number, end:number}}
 */
function extractBlock(content) {
  const text = String(content || '');
  const start = text.indexOf(BEGIN_MARK);
  if (start === -1) return { present: false, body: '', start: -1, end: -1 };
  const end = text.indexOf(END_MARK, start);
  if (end === -1) {
    // 有开始标记没有结束标记：文件被截断或用户手工改坏了。
    // **不要**猜结束位置——报告异常，让调用方决定。
    return { present: false, body: '', start, end: -1, broken: true };
  }
  return {
    present: true,
    body: text.slice(start + BEGIN_MARK.length, end),
    start,
    end: end + END_MARK.length,
  };
}

/**
 * 把 Brief 合并进 AGENTS.md 内容。
 *
 * @param {string} existing      现有 AGENTS.md 全文（可能为空）
 * @param {string} briefText     生成的 Brief 正文
 * @param {object} [meta]        { missionId, fingerprint, missionCount }
 * @returns {{ok:boolean, content:string, action:'created'|'appended'|'replaced'|'unchanged', reason?:string}}
 */
function mergeBrief(existing, briefText, meta = {}) {
  const text = String(existing || '');
  const body = String(briefText || '').trim();
  if (!body) return { ok: false, content: text, action: 'unchanged', reason: 'brief text is empty' };

  const block = [
    BEGIN_MARK,
    '## Mission Context (auto-generated by DshCockpit; edits inside this block are overwritten)',
    META_PREFIX + JSON.stringify({
      missionId: meta.missionId || null,
      missionCount: meta.missionCount || 1,
      fingerprint: meta.fingerprint || null,
    }) + ' -->',
    '',
    body,
    '',
    END_MARK,
  ].join('\n');

  const found = extractBlock(text);

  if (found.broken) {
    // 标记损坏：不猜、不覆盖。返回明确失败让上层提示用户手工处理。
    return {
      ok: false,
      content: text,
      action: 'unchanged',
      reason: 'AGENTS.md contains a begin marker without a matching end marker — refusing to guess (fix by hand)',
    };
  }

  if (found.present) {
    const replaced = text.slice(0, found.start) + block + text.slice(found.end);
    return {
      ok: true,
      content: replaced,
      action: replaced === text ? 'unchanged' : 'replaced',
    };
  }

  // 没有标记：首次同步
  if (text.trim() === '') {
    return { ok: true, content: block + '\n', action: 'created' };
  }
  // **追加**，绝不覆盖用户已有内容
  const sep = text.endsWith('\n') ? '\n' : '\n\n';
  return { ok: true, content: text + sep + block + '\n', action: 'appended' };
}

/**
 * 从 AGENTS.md 内容里移除 Brief 块（撤销同步）。
 * 只删标记块；标记之外逐字节保留。
 */
function removeBrief(existing) {
  const text = String(existing || '');
  const found = extractBlock(text);
  if (!found.present) return { ok: true, content: text, action: 'unchanged' };
  // 连同上下的空行一起收掉，避免留下两行空白
  let before = text.slice(0, found.start).replace(/\n+$/, '\n');
  let after = text.slice(found.end).replace(/^\n+/, '');
  const joined = (before + after).replace(/\n{3,}/g, '\n\n');
  return { ok: true, content: joined, action: 'removed' };
}

/** 读 AGENTS.md 里的同步状态（是否存在 Brief 块、对应哪个 Mission）。 */
function readSyncState(existing) {
  const text = String(existing || '');
  const found = extractBlock(text);
  if (!found.present) return { present: false, missionId: null, fingerprint: null };
  const m = found.body.match(/<!-- dsh-cockpit:meta (\{[\s\S]*?\}) -->/);
  let meta = {};
  if (m) {
    try { meta = JSON.parse(m[1]); } catch { meta = {}; }
  }
  return { present: true, missionId: meta.missionId || null, fingerprint: meta.fingerprint || null };
}

/**
 * 同步 Brief 到 `<workspace>/AGENTS.md`。
 *
 * 注意：这里**直接写文件**而不是走 memory-files.js 的 save(scope)，
 * 因为那个 API 是"整文件覆盖"语义（settings 页的编辑器需要它），
 * 而我们需要"只替换标记块"。共用会需要给 save 加一个 merge 模式，
 * 反而让那个安全边界变复杂。
 * 但**仍然复用**同一个路径约定（<workspace>/AGENTS.md），
 * 所以用户可以同时在设置页看到并编辑结果。
 */
// 官方的指令文件上限（@deepseek-ai/dsh-agent-instructions
// 的 DEFAULT_MAX_SOURCE_BYTES）。超过它整个文件会被忽略——
// 静默失效，用户收不到任何提示。所以我们要在写入前先挡住。
const MAX_INSTRUCTION_BYTES = 1048576;

// 官方的项目根判定标记（projectRootMarkers）。
// 没有 .git 的目录可能不被识别为项目根，于是 <workspace>/AGENTS.md
// 根本不会被加载——这是"Brief 写了但没生效"最可能的真实原因。
const PROJECT_ROOT_MARKERS = ['.git'];

/**
 * 检查工作区是否会因"不像项目根"而让 Brief 静默失效。
 *
 * 这不是拒绝写入（用户可能就是想要一个非 git 工作区），
 * 而是**如实告知风险**——让调用方能提示用户，而不是静默失败。
 */
function inspectWorkspaceRoot(workspaceDir) {
  const warnings = [];
  if (!workspaceDir) return { warnings };
  const looksLikeRoot = PROJECT_ROOT_MARKERS.some((marker) => {
    try { return fs.existsSync(path.join(workspaceDir, marker)); } catch { return false; }
  });
  if (!looksLikeRoot) {
    warnings.push(
      'workspace has no .git — the runtime identifies project roots by .git, '
      + 'so <workspace>/AGENTS.md may not be loaded automatically',
    );
  }
  return { warnings, looksLikeRoot };
}

function syncToWorkspace({ workspaceDir, briefText, meta = {} }) {
  if (!workspaceDir) return { ok: false, reason: 'workspaceDir is required' };
  const file = path.join(workspaceDir, 'AGENTS.md');

  let existing = '';
  try {
    existing = fs.readFileSync(file, 'utf8');
  } catch (err) {
    if (!err || err.code !== 'ENOENT') {
      return { ok: false, reason: `cannot read ${file}: ${err.message}` };
    }
    // 不存在 = 首次同步，existing 保持 ''
  }

  const merged = mergeBrief(existing, briefText, meta);
  if (!merged.ok) return { ok: false, reason: merged.reason, file };
  if (merged.action === 'unchanged') {
    return { ok: true, action: 'unchanged', file };
  }

  // 超过官方上限 = 整个文件被忽略。宁可明确报错，也不要写一个读了等于没读的文件。
  const contentBytes = Buffer.byteLength(merged.content, 'utf8');
  if (contentBytes > MAX_INSTRUCTION_BYTES) {
    return {
      ok: false,
      code: 'INSTRUCTION_TOO_LARGE',
      reason: `AGENTS.md would be ${contentBytes} bytes, over the runtime limit of ${MAX_INSTRUCTION_BYTES}`,
      file,
    };
  }

  // 非致命但重要：没有 .git 时 Brief 可能不被加载
  const rootInfo = inspectWorkspaceRoot(workspaceDir);

  // 原子写：唯一临时名，避免并发互踩
  try {
    const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    // 顺手让 .dsh/ 在自己的 .gitignore 里自我忽略 —— 否则用户的 git status
    // 会看到一堆我们写入的未跟踪文件（详见 workspace-dir.js 的第一性原理）。
    ensureSelfIgnore(path.join(workspaceDir, '.dsh'));
    fs.writeFileSync(tmp, merged.content, 'utf8');
    fs.renameSync(tmp, file);
  } catch (err) {
    return { ok: false, reason: `cannot write ${file}: ${err.message}`, file };
  }

  return { ok: true, action: merged.action, file, warnings: rootInfo.warnings };
}

/** 撤销同步（只删标记块）。 */
function unsyncFromWorkspace({ workspaceDir }) {
  if (!workspaceDir) return { ok: false, reason: 'workspaceDir is required' };
  const file = path.join(workspaceDir, 'AGENTS.md');
  let existing;
  try {
    existing = fs.readFileSync(file, 'utf8');
  } catch (err) {
    if (err && err.code === 'ENOENT') return { ok: true, action: 'no-file', file };
    return { ok: false, reason: err.message, file };
  }
  const removed = removeBrief(existing);
  if (removed.action === 'unchanged') return { ok: true, action: 'unchanged', file };

  try {
    const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
    fs.writeFileSync(tmp, removed.content, 'utf8');
    fs.renameSync(tmp, file);
  } catch (err) {
    return { ok: false, reason: err.message, file };
  }
  return { ok: true, action: 'removed', file };
}

/** 只读：看当前 workspace 的 AGENTS.md 同步到了哪一步。 */
function inspect({ workspaceDir }) {
  if (!workspaceDir) return { ok: false, reason: 'workspaceDir is required' };
  const file = path.join(workspaceDir, 'AGENTS.md');
  let existing;
  try {
    existing = fs.readFileSync(file, 'utf8');
  } catch (err) {
    if (err && err.code === 'ENOENT') {
      return { ok: true, file, exists: false, synced: false, missionId: null };
    }
    return { ok: false, reason: err.message, file };
  }
  const st = readSyncState(existing);
  return { ok: true, file, exists: true, synced: st.present, missionId: st.missionId, fingerprint: st.fingerprint };
}

module.exports = {
  BEGIN_MARK,
  END_MARK,
  extractBlock,
  mergeBrief,
  removeBrief,
  readSyncState,
  syncToWorkspace,
  unsyncFromWorkspace,
  inspect,
  inspectWorkspaceRoot,
  MAX_INSTRUCTION_BYTES,
};
